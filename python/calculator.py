# make a very basic calculator for two numbers performing "+,-,*,/,//,%" operation
a=11
b=3
print("the value of", a,"+",b,"is", a+b)
print("the value of", a,"-",b,"is", a-b)
print("the value of", a,"*",b,"is", a*b)
print("the value of", a,"/",b,"is", a/b)
print("the value of", a,"//",b,"is", a//b)
print("the value of", a,"%",b,"is", a%b)